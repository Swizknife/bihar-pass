export function timeOfDayTip(d: Destination): string {
  if (d.categories.includes('wildlife')) return 'Wildlife is most active at dawn and late afternoon.'
  if (d.id === 'kakolat' || d.categories.includes('natural')) return 'Morning is cooler and less crowded.'
  if (d.categories.includes('religious')) return 'Early morning is calmer and cooler for worship and walking.'
  if (d.categories.includes('historical')) return 'Visit in the morning or late afternoon; midday sun on open ruins is harsh.'
  return 'Morning to early afternoon works well.'
}
